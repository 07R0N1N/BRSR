CREATE OR REPLACE FUNCTION public.can_access_block(
  target_org_id UUID,
  target_block_id TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.brsr_assignment_blocks b
    WHERE b.block_id = target_block_id
      AND public.can_access_question(target_org_id, b.question_code)
  );
$$;

COMMENT ON FUNCTION public.can_access_block(UUID, TEXT) IS
  'True when the caller may access the representative question_code for the block.';

-- Arguments are evaluated in the caller's scope, so an RLS policy cannot
-- accidentally compare brsr_assignment_blocks columns against themselves
-- (an unqualified `b.block_id = block_id` inside EXISTS resolves to b.block_id).
CREATE OR REPLACE FUNCTION public.block_triple_matches(
  target_block_id TEXT,
  target_panel_id TEXT,
  target_question_code TEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.brsr_assignment_blocks b
    WHERE b.block_id = target_block_id
      AND b.panel_id = target_panel_id
      AND b.question_code = target_question_code
  );
$$;

COMMENT ON FUNCTION public.block_triple_matches(TEXT, TEXT, TEXT) IS
  'True when (block_id, panel_id, question_code) is a known row in brsr_assignment_blocks.';

GRANT EXECUTE ON FUNCTION public.block_triple_matches(TEXT, TEXT, TEXT) TO authenticated;

