-- ── Triggers: identity freeze + admin-only resolve ───────────────────────────

CREATE OR REPLACE FUNCTION public.question_threads_guard_update()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.org_id IS DISTINCT FROM OLD.org_id
     OR NEW.reporting_year IS DISTINCT FROM OLD.reporting_year
     OR NEW.block_id IS DISTINCT FROM OLD.block_id
     OR NEW.panel_id IS DISTINCT FROM OLD.panel_id
     OR NEW.question_code IS DISTINCT FROM OLD.question_code THEN
    RAISE EXCEPTION 'question_threads identity columns are immutable'
      USING ERRCODE = '42501';
  END IF;

  IF (NEW.resolved_at IS DISTINCT FROM OLD.resolved_at
      OR NEW.resolved_by IS DISTINCT FROM OLD.resolved_by)
     AND public.current_user_role_slug() NOT IN ('admin', 'master') THEN
    RAISE EXCEPTION 'only admin/master may resolve or reopen threads'
      USING ERRCODE = '42501';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_question_threads_guard_update ON public.question_threads;
CREATE TRIGGER trg_question_threads_guard_update
  BEFORE UPDATE ON public.question_threads
  FOR EACH ROW
  EXECUTE PROCEDURE public.question_threads_guard_update();

-- Author may edit body / soft-delete; admin/master may only soft-delete (not rewrite body).
CREATE OR REPLACE FUNCTION public.question_comments_guard_update()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.thread_id IS DISTINCT FROM OLD.thread_id
     OR NEW.org_id IS DISTINCT FROM OLD.org_id
     OR NEW.author_id IS DISTINCT FROM OLD.author_id
     OR NEW.author_label IS DISTINCT FROM OLD.author_label
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'question_comments identity columns are immutable'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.body IS DISTINCT FROM OLD.body
     OR NEW.edited_at IS DISTINCT FROM OLD.edited_at THEN
    IF OLD.author_id IS DISTINCT FROM auth.uid() THEN
      RAISE EXCEPTION 'only the author may edit comment body'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_question_comments_guard_update ON public.question_comments;
CREATE TRIGGER trg_question_comments_guard_update
  BEFORE UPDATE ON public.question_comments
  FOR EACH ROW
  EXECUTE PROCEDURE public.question_comments_guard_update();

-- Snapshot author_label from profiles at insert (server-side; ignore client value).
CREATE OR REPLACE FUNCTION public.question_comments_set_author_label()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  label TEXT;
BEGIN
  IF NEW.author_id IS NULL THEN
    NEW.author_label := COALESCE(NULLIF(trim(NEW.author_label), ''), 'Unknown');
    RETURN NEW;
  END IF;

  SELECT COALESCE(
    NULLIF(trim(p.display_name), ''),
    NULLIF(trim(p.email), ''),
    NEW.author_id::text
  )
  INTO label
  FROM public.profiles p
  WHERE p.id = NEW.author_id;

  NEW.author_label := COALESCE(label, NEW.author_id::text, 'Unknown');
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_question_comments_set_author_label ON public.question_comments;
CREATE TRIGGER trg_question_comments_set_author_label
  BEFORE INSERT ON public.question_comments
  FOR EACH ROW
  EXECUTE PROCEDURE public.question_comments_set_author_label();

